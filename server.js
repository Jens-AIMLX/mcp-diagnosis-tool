// Build an export directly from a raw snippet (server-side helper for tests)
app.post('/api/export/from-snippet', (req, res) => {
  try {
    const { snippet, serverName, appVersion } = req.body || {};
    if (!snippet || typeof snippet !== 'string') return res.status(400).json({ ok: false, error: { details: 'snippet (string) is required' } });
    // Try parsing
    let parsed;
    try {
      parsed = parseMcpConfigContent(snippet);
    } catch (err) {
      return res.status(400).json({ ok: false, error: { details: `parse failed: ${err.message}` } });
    }

    // Attempt to extract a server spec
    let specObj = null;
    if (parsed && typeof parsed === 'object') {
      if (Array.isArray(parsed.servers) && parsed.servers.length) {
        specObj = parsed.servers[0];
      } else if (parsed.mcpServers && typeof parsed.mcpServers === 'object') {
        // pick by serverName or first
        if (serverName && parsed.mcpServers[serverName]) specObj = parsed.mcpServers[serverName];
        else {
          const keys = Object.keys(parsed.mcpServers);
          if (keys.length) specObj = parsed.mcpServers[keys[0]];
        }
      }
      // If parsed itself looks like a server spec
      if (!specObj && (parsed.mode || parsed.command || parsed.url || parsed.args)) {
        specObj = parsed;
      }
    }

    if (!specObj) return res.status(400).json({ ok: false, error: { details: 'No server spec found in snippet' } });

    const artifacts = buildExportTemplate({ spec: specObj, serverName: serverName || specObj.name || 'server', appVersion: appVersion || process.env.APP_VERSION || 'dev' });
    return res.json({ ok: true, ...artifacts, parsed });
  } catch (err) {
    logError('export_from_snippet_error', err);
    res.status(500).json({ ok: false, error: { details: err.message } });
  }
});

// Save exported workflow artifacts into a server-side folder with proper subdirectories
// Body: { baseName: string, targets: [{ name: 'MCPflow/..'|'APIflow/..'|'json/..', content: string, mime?: string }] }
// Returns: { ok: true, folder: relativePath, absoluteFolder: string, files: string[] }
app.post('/api/export/save', (req, res) => {
  try {
    const { baseName, targets } = req.body || {};
    if (!baseName || !Array.isArray(targets) || !targets.length) {
      return res.status(400).json({ ok: false, error: { details: 'baseName and targets array are required' } });
    }
    const rootDir = path.join(__dirname, 'imports', 'exports', String(baseName));
    try { fs.mkdirSync(rootDir, { recursive: true }); } catch (_) {}
    const written = [];
    for (const t of targets) {
      if (!t || typeof t.name !== 'string' || typeof t.content !== 'string') continue;
      // Normalize and ensure path stays within rootDir
      const safeName = t.name.replace(/\\/g, '/');
      if (safeName.includes('..')) {
        return res.status(400).json({ ok: false, error: { details: 'Invalid file path' } });
      }
      const absPath = path.join(rootDir, safeName);
      const dir = path.dirname(absPath);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(absPath, t.content, { encoding: 'utf8' });
      written.push(absPath);
    }
    return res.json({ ok: true, folder: path.join('imports', 'exports', String(baseName)), absoluteFolder: rootDir, files: written });
  } catch (err) {
    logError('export_save_error', err);
    return res.status(500).json({ ok: false, error: { details: err.message } });
  }
});

