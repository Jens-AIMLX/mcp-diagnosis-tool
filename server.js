// Small helper to create simple export artifacts on the server side so clients
// (or automated tests) can validate export logic without relying on the browser
// File format mirrors what the client exports: YAML, JS, PY and a baseName
function buildExportTemplate({ spec = {}, serverName = 'server', appVersion = 'dev' } = {}) {
  const displayName = serverName || (spec?.url || spec?.command || 'server');
  const baseName = `${displayName.replace(/[^a-zA-Z0-9_-]/g, '_')}_${new Date().toISOString().replace(/[:.]/g, '-')}_session`;

  const snippetCommentYaml = `# Exported with MCP Diagnosis Tool v ${appVersion}\n`;
  const workflow = {
    version: 1,
    exported_at: new Date().toISOString(),
    server: { name: displayName, spec },
    steps: []
  };

  // simple YAML using single quoted style (reuse client logic lightly)
  function yamlScalar(v) {
    if (v === null || v === undefined) return 'null';
    if (typeof v === 'string') return `'${String(v).replace(/'/g, "''")}'`;
    if (typeof v === 'boolean') return v ? 'true' : 'false';
    return String(v);
  }
  function toSingleQuotedYAML(obj, indent = 0) {
    const pad = '  '.repeat(indent);
    if (Array.isArray(obj)) {
      if (obj.length === 0) return pad + '[]';
      return obj.map(i => `${pad}- ${typeof i === 'object' ? '\n' + toSingleQuotedYAML(i, indent + 1) : yamlScalar(i)}`).join('\n');
    }
    if (obj && typeof obj === 'object') {
      const keys = Object.keys(obj);
      if (!keys.length) return pad + '{}';
      return keys.map(k => {
        const v = obj[k];
        const key = /^[A-Za-z0-9_]+$/.test(k) ? k : `'${String(k).replace(/'/g, "''")}'`;
        if (v && typeof v === 'object') return `${pad}${key}:\n${toSingleQuotedYAML(v, indent + 1)}`;
        return `${pad}${key}: ${yamlScalar(v)}`;
      }).join('\n');
    }
    return pad + yamlScalar(obj);
  }

  const yaml = snippetCommentYaml + toSingleQuotedYAML(workflow) + '\n';

  const js = `/* Generated by MCP Diagnosis Tool: server-side template (v ${appVersion}) */\n` +
    `const spec = ${JSON.stringify(spec, null, 2)};\n` +
    `// Steps are empty in template\n` +
    `const steps = [];\n` +
    `async function run(){ console.log('No steps defined. Spec:', spec); }\n` +
    `module.exports = { spec, steps, run };\n`;

  const py = `# Generated by MCP Diagnosis Tool: server-side template (v ${appVersion})\n` +
    `spec = ${JSON.stringify(spec, null, 2)}\n` +
    `steps = []\n` +
    `def run():\n` +
    `    print('No steps defined. Spec:', spec)\n` +
    `if __name__ == '__main__':\n` +
    `    run()\n`;

  // Build API-oriented export artifacts that call the MCP Diagnosis HTTP API
  // These scripts do NOT launch MCP servers directly; they call the diagnosis
  // server endpoints to open sessions and replay calls.
  const apiYaml = `# API replay manifest for MCP Diagnosis Tool v ${appVersion}\n` +
    `# Contains high-level steps to reproduce a session via the diagnosis server API\n` +
    `server: ${displayName}\n` +
    `spec: ${JSON.stringify(spec, null, 2)}\n` +
    `steps: []\n`;

  const apiJs = `// API replay script for MCP Diagnosis Tool v ${appVersion}\n` +
    `// This script calls the local MCP Diagnosis HTTP API to open a session and run tools.\n` +
    `// Usage: node ${baseName}.api.js --server http://localhost:3060\n` +
    `const fetch = require('node-fetch');\n` +
    `(async function(){\n` +
    `  const base = process.argv[2] || 'http://localhost:3060';\n` +
    `  const spec = ${JSON.stringify(spec, null, 2)};\n` +
    `  console.log('Opening session for spec', spec);\n` +
    `  const open = await fetch(base + '/api/sessions/open', { method: 'POST', headers: { 'Content-Type':'application/json' }, body: JSON.stringify({ spec }) });\n` +
    `  const o = await open.json();\n` +
    `  if (!o || !o.sessionId) { console.error('Failed to open session', o); process.exit(2); }\n` +
    `  const sessionId = o.sessionId;\n` +
    `  console.log('Session opened', sessionId);\n` +
    `  // No steps defined in template. Replace with calls to POST /api/tools/call if needed.\n` +
    `  // Example: await fetch(base + '/api/tools/call', { method: 'POST', headers: {'Content-Type':'application/json'}, body: JSON.stringify({ sessionId, tool: 'toolName', args: {} }) });\n` +
    `  // Close the session when done\n` +
    `  await fetch(base + '/api/sessions/close', { method: 'POST', headers: { 'Content-Type':'application/json' }, body: JSON.stringify({ sessionId }) });\n` +
    `  console.log('Session closed');\n` +
    `})();\n`;

  const apiPs = `# API replay PowerShell script for MCP Diagnosis Tool v ${appVersion}\n` +
    `# Usage: powershell -File ${baseName}.api.ps1 -BaseUrl http://localhost:3060\n` +
    `$BaseUrl = $args[0] ; if (-not $BaseUrl) { $BaseUrl = 'http://localhost:3060' }\n` +
    `$spec = ${JSON.stringify(spec, null, 2)}\n` +
    `Write-Host "Opening session for spec via $BaseUrl"\n` +
    `$resp = Invoke-RestMethod -Method Post -Uri ($BaseUrl + '/api/sessions/open') -ContentType 'application/json' -Body (ConvertTo-Json @{ spec = $spec } -Depth 10)\n` +
    `if (-not $resp.sessionId) { Write-Error "Failed to open session: $($resp | ConvertTo-Json -Depth 5)" ; exit 2 }\n` +
    `$sessionId = $resp.sessionId\n` +
    `Write-Host "Session opened: $sessionId"\n` +
    `# No steps defined in template. Use Invoke-RestMethod -Uri ($BaseUrl + '/api/tools/call') -Method Post -ContentType 'application/json' -Body (ConvertTo-Json @{ sessionId = $sessionId; tool='toolName'; args=@{} } -Depth 10)\n` +
    `Write-Host "Closing session"\n` +
    `Invoke-RestMethod -Method Post -Uri ($BaseUrl + '/api/sessions/close') -ContentType 'application/json' -Body (ConvertTo-Json @{ sessionId = $sessionId } -Depth 5)\n`;

  return { yaml, js, py, apiYaml, apiJs, apiPs, baseName };
}

